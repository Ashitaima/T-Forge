/** Коди, впорядковані за українською назвою — саме так їх показує список. */
export const COUNTRY_CODES = Object.keys(COUNTRY_NAMES).sort((first, second) =>
  COUNTRY_NAMES[first].localeCompare(COUNTRY_NAMES[second], "uk")
);

export const isKnownCountry = (code: string | null | undefined): boolean =>
  Boolean(code && code in COUNTRY_NAMES);

/** Підпис для значення з бекенда, яке може бути й невідомим (старі дані). */
export const countryName = (code: string | null | undefined): string =>
  (code && COUNTRY_NAMES[code]) || code || "";

/**
 * Прапор як пара regional indicator: 'UA' → 🇺🇦. Емодзі, а не картинка, —
 * щоб не тягнути ані зовнішній спрайт, ані сімдесят вбудованих SVG.
 *
 * Windows не має гліфів прапорів у системному шрифті й малює замість них пару
 * літер («UA»). Це не поламаний інтерфейс: код країни лишається читабельним,
 * і поруч усе одно стоїть назва або сам код. На macOS, Linux, Android та в
 * Firefox під Windows видно справжній прапор.
 */
export const countryFlag = (code: string | null | undefined): string => {
  if (!isKnownCountry(code)) {
    return "";
  }

  return String.fromCodePoint(
    ...code!.split("").map((letter) => 0x1f1e6 + letter.charCodeAt(0) - 65)
  );
};
